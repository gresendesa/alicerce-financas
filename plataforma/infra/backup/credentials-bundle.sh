#!/usr/bin/env bash
set -Eeuo pipefail

# Interface operacional do bundle. O consumidor deve usar install; não deve
# abrir o arquivo nem redirecionar a saída deste script para logs.
FORMAT='postgres-restic-bundle-v1'
SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"

die() { echo "Error: $*" >&2; exit 1; }
b64() { base64 -d; }

usage() {
  cat <<'USAGE'
Usage:
  credentials-bundle.sh create [OUTPUT_FILE]
  credentials-bundle.sh validate BUNDLE_FILE
  credentials-bundle.sh install BUNDLE_FILE [TARGET_DIR]

create uses ENV_FILE and SECRETS_DIR. install uses TARGET_DIR or ./ops/backup.
USAGE
}

load_env() {
  local env_file="${ENV_FILE:-$SCRIPT_DIR/.env}"
  [[ -f "$env_file" ]] || die "missing ENV_FILE"
  set -a
  # shellcheck disable=SC1090
  . "$env_file"
  set +a
}

create_bundle() {
  local output="${1:-/tmp/postgres-restic-${BACKUP_ENVIRONMENT:-environment}-${DB_NAME:-postgres}-bundle.txt}"
  local secrets="${SECRETS_DIR:-$SCRIPT_DIR/secrets}" tmp name value
  load_env
  [[ ! -e "$output" ]] || die "refusing to overwrite output"
  for name in restic-password postgres-password aws-credentials; do
    [[ -f "$secrets/$name" ]] || die "missing secret file"
  done
  : "${AWS_DEFAULT_REGION:?missing AWS_DEFAULT_REGION}"
  : "${RESTIC_REPOSITORY:?missing RESTIC_REPOSITORY}"
  : "${DB_HOST:?missing DB_HOST}"
  : "${DB_PORT:=5432}"
  : "${DB_NAME:?missing DB_NAME}"
  : "${DB_USER:?missing DB_USER}"
  : "${BACKUP_ENVIRONMENT:?missing BACKUP_ENVIRONMENT}"
  umask 077
  tmp="$(mktemp "$output.tmp.XXXXXX")"
  trap 'rm -f "$tmp"' EXIT
  {
    printf '%s\n' "# $FORMAT"
    for name in AWS_DEFAULT_REGION RESTIC_REPOSITORY DB_HOST DB_PORT DB_NAME DB_USER BACKUP_ENVIRONMENT BACKUP_NETWORK BACKUP_INTERVAL_SECONDS BACKUP_RETRY_SECONDS RESTIC_KEEP_LAST RESTIC_KEEP_DAILY RESTIC_KEEP_WEEKLY RESTIC_KEEP_MONTHLY; do
      value="${!name:-}"
      printf '%s_b64=%s\n' "$name" "$(printf '%s' "$value" | base64 | tr -d '\n')"
    done
    printf 'RESTIC_PASSWORD_b64=%s\n' "$(sed -n '1p' "$secrets/restic-password" | base64 | tr -d '\n')"
    printf 'DB_PASSWORD_b64=%s\n' "$(sed -n '1p' "$secrets/postgres-password" | base64 | tr -d '\n')"
    printf 'AWS_ACCESS_KEY_ID_b64=%s\n' "$(sed -n 's/^[[:space:]]*aws_access_key_id[[:space:]]*=[[:space:]]*//p' "$secrets/aws-credentials" | head -n1 | base64 | tr -d '\n')"
    printf 'AWS_SECRET_ACCESS_KEY_b64=%s\n' "$(sed -n 's/^[[:space:]]*aws_secret_access_key[[:space:]]*=[[:space:]]*//p' "$secrets/aws-credentials" | head -n1 | base64 | tr -d '\n')"
  } > "$tmp"
  chmod 600 "$tmp"; mv "$tmp" "$output"; trap - EXIT
  echo "Bundle created: $output"
}

declare -A F=()
read_bundle() {
  local file="$1" line key value
  [[ -f "$file" ]] || die "missing bundle"
  IFS= read -r line < "$file"; [[ "$line" == "# $FORMAT" ]] || die "unsupported bundle format"
  while IFS= read -r line; do
    key="${line%%=*}"
    value="${line#*=}"
    [[ -z "$key" ]] && continue
    [[ "$key" == *_b64 ]] || die "invalid bundle field"
    F["$key"]="$value"
  done < <(tail -n +2 "$file")
}

value() {
  local key="$1"
  [[ -v "F[$key]" ]] || die "missing bundle field"
  printf '%s' "${F[$key]}" | b64
}

validate_bundle() {
  local file="$1" key
  read_bundle "$file"
  for key in AWS_DEFAULT_REGION RESTIC_REPOSITORY DB_HOST DB_PORT DB_NAME DB_USER BACKUP_ENVIRONMENT BACKUP_NETWORK BACKUP_INTERVAL_SECONDS BACKUP_RETRY_SECONDS RESTIC_KEEP_LAST RESTIC_KEEP_DAILY RESTIC_KEEP_WEEKLY RESTIC_KEEP_MONTHLY RESTIC_PASSWORD DB_PASSWORD AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY; do
    value "${key}_b64" >/dev/null || die "invalid encoded value"
  done
  echo 'Bundle valid.'
}

install_bundle() {
  local file="$1" target secrets key
  local env_tmp restic_tmp db_tmp aws_tmp
  target="${2:-${TARGET_DIR:-ops/backup}}"
  secrets="$target/secrets"
  validate_bundle "$file" >/dev/null
  [[ ! -e "$target/.env" ]] || die 'refusing to overwrite existing .env'
  [[ ! -e "$secrets" ]] || die 'refusing to overwrite existing secrets directory'
  mkdir -p "$secrets"; chmod 700 "$secrets"; umask 077
  env_tmp="$(mktemp "$target/.env.tmp.XXXXXX")"
  restic_tmp="$(mktemp "$secrets/.restic-password.XXXXXX")"
  db_tmp="$(mktemp "$secrets/.postgres-password.XXXXXX")"
  aws_tmp="$(mktemp "$secrets/.aws-credentials.XXXXXX")"
  trap 'rm -f "$env_tmp" "$restic_tmp" "$db_tmp" "$aws_tmp"' EXIT
  {
    printf '%s\n' '# Generated by credentials-bundle.sh. Do not commit.'
    for key in AWS_DEFAULT_REGION RESTIC_REPOSITORY DB_HOST DB_PORT DB_NAME DB_USER BACKUP_ENVIRONMENT BACKUP_NETWORK BACKUP_INTERVAL_SECONDS BACKUP_RETRY_SECONDS RESTIC_KEEP_LAST RESTIC_KEEP_DAILY RESTIC_KEEP_WEEKLY RESTIC_KEEP_MONTHLY; do
      printf '%s=%s\n' "$key" "$(value "${key}_b64")"
    done
    printf '%s\n' RESTIC_PASSWORD_FILE=/run/secrets/restic-password RESTIC_CACHE_DIR=/tmp/restic-cache DB_PASSWORD_FILE=/run/secrets/postgres-password AWS_SHARED_CREDENTIALS_FILE=/run/secrets/aws-credentials
  } > "$env_tmp"
  value RESTIC_PASSWORD_b64 > "$restic_tmp"; value DB_PASSWORD_b64 > "$db_tmp"
  { printf '%s\n' '[default]'; printf 'aws_access_key_id = %s\n' "$(value AWS_ACCESS_KEY_ID_b64)"; printf 'aws_secret_access_key = %s\n' "$(value AWS_SECRET_ACCESS_KEY_b64)"; } > "$aws_tmp"
  chmod 600 "$env_tmp" "$restic_tmp" "$db_tmp" "$aws_tmp"
  mv "$env_tmp" "$target/.env"; mv "$restic_tmp" "$secrets/restic-password"; mv "$db_tmp" "$secrets/postgres-password"; mv "$aws_tmp" "$secrets/aws-credentials"
  trap - EXIT
  echo "Bundle installed: $target"
}

case "${1:-}" in
  create) create_bundle "${2:-}" ;;
  validate) [[ $# -eq 2 ]] || { usage >&2; exit 2; }; validate_bundle "$2" ;;
  install) [[ $# -ge 2 && $# -le 3 ]] || { usage >&2; exit 2; }; install_bundle "$2" "${3:-}" ;;
  -h|--help) usage ;;
  *) usage >&2; exit 2 ;;
esac
